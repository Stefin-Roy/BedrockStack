// ── atomics for VRAM geometry + cursor ────────────────────────────────
static FB_VA: AtomicU64 = AtomicU64::new(0);
static FB_W: AtomicUsize = AtomicUsize::new(0);
static FB_H: AtomicUsize = AtomicUsize::new(0);
static FB_STRIDE: AtomicUsize = AtomicUsize::new(0);
static FB_BPP: AtomicUsize = AtomicUsize::new(0);
static FB_PF_BGR: AtomicBool = AtomicBool::new(true); // true=Bgr false=Rgb
static FB_READY: AtomicBool = AtomicBool::new(false);
static FB_OWNER: AtomicBool = AtomicBool::new(false);

static CUR_X: AtomicUsize = AtomicUsize::new(0);
static CUR_Y: AtomicUsize = AtomicUsize::new(0);
static CUR_COL: AtomicUsize = AtomicUsize::new(0);

const BANNER_H: usize = 24;
const CHAR_W: usize = 8;
const CHAR_H: usize = 16;

#[inline]
fn cols() -> usize {
    let w = FB_W.load(Ordering::Relaxed);
    if w >= 1600 {
        2
    } else {
        1
    }
}
#[inline]
fn col_w_px() -> usize {
    let w = FB_W.load(Ordering::Relaxed);
    let c = cols();
    if c == 0 { w } else { w / c }
}
#[inline]
fn col_start(col: usize) -> usize {
    col * col_w_px()
}
#[inline]
fn col_end(col: usize) -> usize {
    (col + 1) * col_w_px()
}

// Colors — direct RGB tuples
const BG_R: u8 = 0x8B;
const BG_G: u8 = 0x00;
const BG_B: u8 = 0x00;
const FG_R: u8 = 0xFF;
const FG_G: u8 = 0xFF;
const FG_B: u8 = 0xFF;

#[inline]
fn sfence() {
    unsafe { core::arch::asm!("sfence", options(nostack, preserves_flags, nomem)) }
}

#[inline]
fn pixel_bytes(r: u8, g: u8, b: u8, is_bgr: bool) -> [u8; 4] {
    if is_bgr {
        [b, g, r, 255]
    } else {
        [r, g, b, 255]
    }
}

#[inline]
fn write_pixel(buf: *mut u8, off: usize, bpp: usize, px: &[u8; 4]) {
    unsafe {
        match bpp {
            4 => *(buf.add(off) as *mut u32) = u32::from_le_bytes(*px),
            2 => *(buf.add(off) as *mut u16) = u16::from_le_bytes([px[0], px[1]]),
            _ => {
                for i in 0..bpp {
                    *buf.add(off + i) = px[i];
                }
            }
        }
    }
}

/// Try to claim the panic screen for this CPU. True if we are the owner.
pub fn claim() -> bool {
    FB_OWNER
        .compare_exchange(false, true, Ordering::AcqRel, Ordering::Relaxed)
        .is_ok()
}

/// True if panic screen is ready for `panic_puts`.
pub fn is_ready() -> bool {
    FB_READY.load(Ordering::Relaxed) && FB_VA.load(Ordering::Relaxed) != 0
}

/// Initialize panic screen from `display::get()`. Must be called with
/// interrupts disabled on the faulting CPU before any `panic_puts`.
///
/// Returns true if VRAM is now owned and ready. First caller wins; later
/// callers get false and should use serial only.
pub fn panic_screen_init() -> bool {
    if !claim() {
        return false;
    }
    let dev = match crate::display::get() {
        Some(d) => d,
        None => return false,
    };
    if dev.va == 0 || dev.width == 0 || dev.height == 0 || dev.bpp == 0 {
        return false;
    }
    FB_VA.store(dev.va, Ordering::Relaxed);
    FB_W.store(dev.width as usize, Ordering::Relaxed);
    FB_H.store(dev.height as usize, Ordering::Relaxed);
    FB_STRIDE.store(dev.stride as usize, Ordering::Relaxed);
    FB_BPP.store(dev.bpp as usize, Ordering::Relaxed);
    FB_PF_BGR.store(matches!(dev.pixel_format, PixelFormat::Bgr), Ordering::Relaxed);
    CUR_COL.store(0, Ordering::Relaxed);
    CUR_X.store(0, Ordering::Relaxed);
    CUR_Y.store(BANNER_H, Ordering::Relaxed);
    FB_READY.store(true, Ordering::Relaxed);

    // Clear whole VRAM to MCE red ASAP — this is the first visible sign.
    clear_screen();
    // Vertical separator for 2-col mode
    if cols() > 1 {
        let cw = col_w_px();
        // 1px dark line between columns
        //fill_rect_raw(cw, BANNER_H, 1, dev.height as usize - BANNER_H, 0x30, 0x00, 0x00);
        // subtle 2nd line for visibility
        if cw + 1 < dev.width as usize {
            fill_rect_raw(cw + 1, BANNER_H, 1, dev.height as usize - BANNER_H, 0x60, 0x00, 0x00);
        }
    }
    // Reset cursor below banner at column 0
    CUR_COL.store(0, Ordering::Relaxed);
    CUR_X.store(0, Ordering::Relaxed);
    CUR_Y.store(BANNER_H, Ordering::Relaxed);
    sfence();
    // Show the 2-4 serial lines that immediately preceded the fault (via
    // the capture ring, lock-free try). This mirrors the user's example:
    //   [CPU0] [storage] ahci probe ...
    //   ===== #PF =====
    // Limited to 4 lines / 1 KiB, no heap, no IRQ.
    {
        struct ScreenWriter;
        impl core::fmt::Write for ScreenWriter {
            fn write_str(&mut self, s: &str) -> core::fmt::Result {
                panic_puts(s);
                Ok(())
            }
        }
        let mut w = ScreenWriter;
        let _ = core::fmt::write(&mut w, format_args!("--- Last Log (4 lines) ---\n"));
        if !crate::drivers::serial::try_dump_last_lines(&mut w, 4) {
            let _ = core::fmt::write(&mut w, format_args!("(log unavailable: contended)\n"));
        }
        let _ = core::fmt::write(&mut w, format_args!("\n"));
    }
    true
}

fn clear_screen() {
    let va = FB_VA.load(Ordering::Relaxed);
    let w = FB_W.load(Ordering::Relaxed);
    let h = FB_H.load(Ordering::Relaxed);
    if va == 0 || w == 0 || h == 0 {
        return;
    }
    fill_rect_raw(0, 0, w, h, BG_R, BG_G, BG_B);
    sfence();
}

fn fill_rect_raw(x: usize, y: usize, w: usize, h: usize, r: u8, g: u8, b: u8) {
    let va = FB_VA.load(Ordering::Relaxed) as *mut u8;
    let stride = FB_STRIDE.load(Ordering::Relaxed);
    let bpp = FB_BPP.load(Ordering::Relaxed);
    let fb_w = FB_W.load(Ordering::Relaxed);
    let fb_h = FB_H.load(Ordering::Relaxed);
    let is_bgr = FB_PF_BGR.load(Ordering::Relaxed);
    if va.is_null() || w == 0 || h == 0 || stride == 0 || bpp == 0 {
        return;
    }
    if x >= fb_w || y >= fb_h {
        return;
    }
    let x2 = (x + w).min(fb_w);
    let y2 = (y + h).min(fb_h);
    let px = pixel_bytes(r, g, b, is_bgr);
    let fill_w = x2 - x;
    if fill_w == 0 {
        return;
    }
    // Fast path for 4bpp: fill via u32 slice per row
    if bpp == 4 {
        let pixel = u32::from_le_bytes(px);
        for row in y..y2 {
            let off = row * stride * bpp + x * bpp;
            unsafe {
                let ptr = va.add(off) as *mut u32;
                // `fill_w` is pixels, row is contiguous
                core::slice::from_raw_parts_mut(ptr, fill_w).fill(pixel);
            }
        }
        return;
    }
    for row in y..y2 {
        let mut base = row * stride * bpp + x * bpp;
        for _ in 0..fill_w {
            write_pixel(va, base, bpp, &px);
            base += bpp;
        }
    }
}

fn scroll_up_one_line() {
    let va = FB_VA.load(Ordering::Relaxed) as *mut u8;
    let w = FB_W.load(Ordering::Relaxed);
    let h = FB_H.load(Ordering::Relaxed);
    let stride = FB_STRIDE.load(Ordering::Relaxed);
    let bpp = FB_BPP.load(Ordering::Relaxed);
    if va.is_null() || h <= BANNER_H + CHAR_H {
        return;
    }
    let row_bytes = stride * bpp;
    // Preserve banner at top — scroll only region [BANNER_H, h)
    let banner_bytes = BANNER_H * row_bytes;
    let src_off = (BANNER_H + CHAR_H) * row_bytes;
    let copy_bytes = (h - BANNER_H - CHAR_H) * row_bytes;
    unsafe {
        core::ptr::copy(va.add(src_off), va.add(banner_bytes), copy_bytes);
        let bottom_off = banner_bytes + copy_bytes;
        let clear_bytes = CHAR_H * row_bytes;
        core::ptr::write_bytes(va.add(bottom_off), 0, clear_bytes);
    }
    // recolor cleared bottom strip to BG
    let bottom_y = h - CHAR_H;
    fill_rect_raw(0, bottom_y, w, CHAR_H, BG_R, BG_G, BG_B);
    // redraw column separators in bottom strip if 2-col
    if cols() > 1 {
        let cw = col_w_px();
        fill_rect_raw(cw, bottom_y, 1, CHAR_H, 0x30, 0x00, 0x00);
        if cw + 1 < w {
            fill_rect_raw(cw + 1, bottom_y, 1, CHAR_H, 0x60, 0x00, 0x00);
        }
    }
    sfence();
}

fn draw_glyph_at(x: usize, y: usize, ch: u8) {
    let va = FB_VA.load(Ordering::Relaxed) as *mut u8;
    let stride = FB_STRIDE.load(Ordering::Relaxed);
    let bpp = FB_BPP.load(Ordering::Relaxed);
    let w = FB_W.load(Ordering::Relaxed);
    let h = FB_H.load(Ordering::Relaxed);
    let is_bgr = FB_PF_BGR.load(Ordering::Relaxed);
    if va.is_null() || x >= w || y >= h || ch >= 128 || stride == 0 || bpp == 0 {
        return;
    }
    let glyph = FONT[ch as usize];
    let fg = pixel_bytes(FG_R, FG_G, FG_B, is_bgr);
    let bg = pixel_bytes(BG_R, BG_G, BG_B, is_bgr);
    for row in 0..16 {
        let py = y + row;
        if py >= h {
            break;
        }
        let base = py * stride * bpp + x * bpp;
        if base + 8 * bpp > (stride * bpp * h) {
            break;
        }
        for col in 0..8 {
            let px = x + col;
            if px >= w {
                break;
            }
            let bit = (glyph[row] >> (7 - col)) & 1;
            let p = if bit != 0 { fg } else { bg };
            write_pixel(va, base + col * bpp, bpp, &p);
        }
    }
}

/// Lock-free puts to VRAM. No-op if `panic_screen_init` was not called or
/// we are not the owner. Handles `\n`, column wrap, and 2-column paged layout.
pub fn panic_puts(s: &str) {
    if !is_ready() {
        return;
    }
    let w = FB_W.load(Ordering::Relaxed);
    let h = FB_H.load(Ordering::Relaxed);
    if w == 0 || h == 0 {
        return;
    }
    let c = cols();
    for b in s.bytes() {
        match b {
            b'\n' => {
                let cur = CUR_COL.load(Ordering::Relaxed);
                let y = CUR_Y.load(Ordering::Relaxed) + CHAR_H;
                if y + CHAR_H > h {
                    if cur + 1 < c {
                        let nc = cur + 1;
                        CUR_COL.store(nc, Ordering::Relaxed);
                        CUR_X.store(col_start(nc), Ordering::Relaxed);
                        CUR_Y.store(BANNER_H, Ordering::Relaxed);
                    } else {
                        scroll_up_one_line();
                        CUR_Y.store(h - CHAR_H, Ordering::Relaxed);
                        CUR_X.store(col_start(cur), Ordering::Relaxed);
                    }
                } else {
                    CUR_Y.store(y, Ordering::Relaxed);
                    CUR_X.store(col_start(cur), Ordering::Relaxed);
                }
            }
            b'\r' => {
                let cur = CUR_COL.load(Ordering::Relaxed);
                CUR_X.store(col_start(cur), Ordering::Relaxed);
            }
            0x08 => {
                let cur = CUR_COL.load(Ordering::Relaxed);
                let start = col_start(cur);
                let x = CUR_X.load(Ordering::Relaxed);
                if x >= start + CHAR_W {
                    CUR_X.store(x - CHAR_W, Ordering::Relaxed);
                }
            }
            _ => {
                let ch = if b < 32 || b >= 128 { b'?' } else { b };
                let cur = CUR_COL.load(Ordering::Relaxed);
                let x = CUR_X.load(Ordering::Relaxed);
                let y = CUR_Y.load(Ordering::Relaxed);
                let end = col_end(cur);
                if x + CHAR_W > end {
                    // wrap within column
                    let y2 = y + CHAR_H;
                    if y2 + CHAR_H > h {
                        if cur + 1 < c {
                            let nc = cur + 1;
                            CUR_COL.store(nc, Ordering::Relaxed);
                            CUR_X.store(col_start(nc), Ordering::Relaxed);
                            CUR_Y.store(BANNER_H, Ordering::Relaxed);
                            draw_glyph_at(col_start(nc), BANNER_H, ch);
                            CUR_X.store(col_start(nc) + CHAR_W, Ordering::Relaxed);
                        } else {
                            scroll_up_one_line();
                            let ry = h - CHAR_H;
                            CUR_Y.store(ry, Ordering::Relaxed);
                            let rx = col_start(cur);
                            CUR_X.store(rx, Ordering::Relaxed);
                            draw_glyph_at(rx, ry, ch);
                            CUR_X.store(rx + CHAR_W, Ordering::Relaxed);
                        }
                    } else {
                        CUR_Y.store(y2, Ordering::Relaxed);
                        let rx = col_start(cur);
                        CUR_X.store(rx, Ordering::Relaxed);
                        draw_glyph_at(rx, y2, ch);
                        CUR_X.store(rx + CHAR_W, Ordering::Relaxed);
                    }
                } else {
                    draw_glyph_at(x, y, ch);
                    CUR_X.store(x + CHAR_W, Ordering::Relaxed);
                }
            }
        }
    }
    sfence();
}

pub fn panic_put_hex(val: u64) {
    if !is_ready() {
        return;
    }
    // 16 hex digits without prefix, lower-case
    if val == 0 {
        panic_puts("0");
        return;
    }
    let mut buf = [0u8; 16];
    let mut i = 16;
    let mut v = val;
    while v != 0 {
        i -= 1;
        let d = (v & 0xF) as u8;
        buf[i] = if d < 10 { b'0' + d } else { b'a' + d - 10 };
        v >>= 4;
    }
    // SAFETY: buf is valid utf8 hex
    let s = unsafe { core::str::from_utf8_unchecked(&buf[i..]) };
    panic_puts(s);
}

/// Write a 0x-prefixed 18-char hex (like {:#018x}) directly to screen.
pub fn panic_put_hex_prefixed(val: u64) {
    panic_puts("0x");
    // pad to 16 hex digits
    let mut buf = [b'0'; 16];
    let mut v = val;
    for j in (0..16).rev() {
        let d = (v & 0xF) as u8;
        buf[j] = if d < 10 { b'0' + d } else { b'a' + d - 10 };
        v >>= 4;
    }
    let s = unsafe { core::str::from_utf8_unchecked(&buf) };
    panic_puts(s);
}
